#!/usr/bin/env python3
"""CandyOS wallpapers: generate the system wallpaper set from assets/wallpapers.

Reads every image in assets/wallpapers/ and regenerates two generated
(never hand-edited) locations in this repo:

  vendor/candyos/overlay/frameworks/base/core/res/res/
      drawable-nodpi/default_wallpaper.<ext>          (from default.jpg)
      drawable-sw600dp-nodpi/default_wallpaper.<ext>
      drawable-sw720dp-nodpi/default_wallpaper.<ext>
    The CandyOS framework overlay (registered as a PRODUCT_PACKAGE_OVERLAY
    by patches/vendor-lineage) overriding the framework-res default wallpaper
    - i.e. THE system default wallpaper - with assets/wallpapers/default.

  apps/CandyExperience/res/
      drawable-nodpi/candyos_wp_<name>.<ext>           (every image)
      values/candyos_wallpapers.xml                     (string-array of names)
    The bundled wallpapers the CandyOS Experience "Wallpapers" screen lists
    and applies (system + lock screen; the app is platform-signed).

With a LineageOS tree argument the freshly generated copies are ALSO pushed
into the tree (vendor/candyos overlay dir + the SetupWizard app slot), so
"edit assets/wallpapers, re-run this script, rebuild" updates a standing
tree without a full candyos-sync.sh. candyos-sync.sh runs this script on
every sync anyway - the folder is the only thing you ever edit.

Usage: candyos-gen-wallpapers.py [<lineage-tree>]
"""

import os
import re
import shutil
import sys
import xml.etree.ElementTree as ET

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(SCRIPT_DIR)
ASSETS = os.path.join(REPO, "assets", "wallpapers")

OVERLAY_RES = os.path.join(REPO, "vendor", "candyos", "overlay",
                          "frameworks", "base", "core", "res", "res")
DEFAULT_BUCKETS = ("drawable-nodpi", "drawable-sw600dp-nodpi",
                   "drawable-sw720dp-nodpi")

APP_RES = os.path.join(REPO, "apps", "CandyExperience", "res")
APP_WALLPAPERS_DIR = os.path.join(APP_RES, "drawable-nodpi")
APP_WALLPAPERS_XML = os.path.join(APP_RES, "values", "candyos_wallpapers.xml")

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp", ".gif"}

TREE_OVERLAY = "vendor/candyos"
TREE_APP = "packages/apps/SetupWizard"


def die(msg):
    print(f"candyos: ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def res_name(name):
    """Sanitize a file base name into a legal Android resource name."""
    n = re.sub(r"[^a-z0-9_]", "_", name.lower())
    if not re.match(r"[a-z]", n[0]):
        n = "w" + n
    return f"candyos_wp_{n}"


def label(name):
    """Human label from a file base name: wp3526312 -> Wp3526312."""
    return name.replace("_", " ").strip().capitalize()


def collect():
    if not os.path.isdir(ASSETS):
        die("assets/wallpapers/ does not exist")
    files = sorted(f for f in os.listdir(ASSETS)
                   if os.path.splitext(f)[1].lower() in IMAGE_EXTS)
    if not files:
        die("assets/wallpapers/ is empty")
    if "default.jpg" not in files:
        die("assets/wallpapers/default.jpg is missing - it is the system "
            "default wallpaper; name the default exactly default.jpg")
    return files


def clean_generated():
    """Remove exactly the files this script owns, repo-side."""
    if os.path.isdir(OVERLAY_RES):
        shutil.rmtree(os.path.join(REPO, "vendor", "candyos", "overlay"))
    if os.path.isdir(APP_WALLPAPERS_DIR):
        for f in os.listdir(APP_WALLPAPERS_DIR):
            if f.startswith("candyos_wp_"):
                os.remove(os.path.join(APP_WALLPAPERS_DIR, f))
    # values/candyos_wallpapers.xml is regenerated below (not deleted here
    # so a mid-run failure keeps the old set until the new one is complete).


def gen_overlay(default_src):
    ext = os.path.splitext(default_src)[1]
    for bucket in DEFAULT_BUCKETS:
        d = os.path.join(OVERLAY_RES, bucket)
        os.makedirs(d, exist_ok=True)
        shutil.copyfile(default_src, os.path.join(d, f"default_wallpaper{ext}"))
    print(f"candyos: overlay: default_wallpaper{ext} -> {DEFAULT_BUCKETS}")


def gen_app(files):
    os.makedirs(APP_WALLPAPERS_DIR, exist_ok=True)
    os.makedirs(os.path.dirname(APP_WALLPAPERS_XML), exist_ok=True)
    names = []
    for f in files:
        base, ext = os.path.splitext(f)
        r = res_name(base)
        shutil.copyfile(os.path.join(ASSETS, f),
                        os.path.join(APP_WALLPAPERS_DIR, f"{r}{ext}"))
        names.append((r, label(base)))
    # The array drives the CandyOS Experience Wallpapers screen; the base
    # name after the candyos_wp_ prefix is the display label.
    xml = ET.Element("resources")
    comment = ET.Comment(
        " GENERATED by scripts/candyos-gen-wallpapers.py from "
        "assets/wallpapers/ - do not edit; re-run the script instead. ")
    xml.append(comment)
    arr = ET.SubElement(xml, "string-array", {"name": "candyos_wallpapers"})
    for r, _ in names:
        ET.SubElement(arr, "item").text = r
    ET.indent(xml) if hasattr(ET, "indent") else None
    with open(APP_WALLPAPERS_XML, "w", encoding="utf-8") as fh:
        fh.write('<?xml version="1.0" encoding="utf-8"?>\n')
        fh.write(ET.tostring(xml, encoding="unicode"))
        fh.write("\n")
    print(f"candyos: app res: {len(names)} wallpaper(s) "
          f"+ values/candyos_wallpapers.xml")


def push_tree(tree, files):
    """Copy the freshly generated repo state into a standing LineageOS tree."""
    if not os.path.isdir(os.path.join(tree, TREE_APP)):
        die(f"{tree}/{TREE_APP} does not exist - is this a synced CandyOS tree?")
    dst = os.path.join(tree, TREE_OVERLAY)
    shutil.rmtree(dst, ignore_errors=True)
    shutil.copytree(os.path.join(REPO, "vendor", "candyos"), dst)
    print(f"candyos: vendored vendor/candyos -> {dst}")
    # App: whole-dir copy, exactly what candyos-sync.sh vendor_apps does.
    dst = os.path.join(tree, TREE_APP)
    shutil.rmtree(dst)
    shutil.copytree(os.path.join(REPO, "apps", "CandyExperience"), dst)
    print(f"candyos: vendored apps/CandyExperience -> {dst}")
    print(f"candyos: tree updated ({len(files)} wallpapers) - rebuild picks "
          f"up the new set")


def main():
    files = collect()
    clean_generated()
    gen_overlay(os.path.join(ASSETS, "default.jpg"))
    gen_app(files)
    if len(sys.argv) > 1:
        tree = sys.argv[1]
        if not os.path.isdir(os.path.join(tree, ".repo")):
            die(f"'{tree}' is not a repo-initialized LineageOS tree")
        push_tree(tree, files)
    print("candyos: wallpapers regenerated from assets/wallpapers/ "
          "(commit the result in the CandyOS repo)")


if __name__ == "__main__":
    main()